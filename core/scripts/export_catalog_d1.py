"""Export v1's catalog data into SQL for the Worker's D1 database.

Reads the CLEANED snapshot and writes INSERTs for migrations/0003_catalog.sql:

    python scripts/export_catalog_d1.py ~/AIPayGen-Backups/v1-data-cleaned-2026-10-30 ../deploy/d1/catalog.sql
    npx wrangler d1 execute aipaygen --remote --file deploy/d1/catalog.sql

Only public catalog fields are exported. The seed scripts generated ratings,
reviews, call counts and revenue at random, so none of those are exported:
publishing them as real would be fake reviews. Real numbers come from usage.
"""
import json
import sqlite3
import sys
import time
from pathlib import Path

PUBLIC_PRICE_BASE = "https://aipaygen.com"


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(int(v)) if isinstance(v, bool) else repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def rows(db: Path, sql: str):
    c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    c.row_factory = sqlite3.Row
    try:
        return [dict(r) for r in c.execute(sql)]
    finally:
        c.close()


def as_list(v):
    if not v:
        return []
    try:
        x = json.loads(v)
        return x if isinstance(x, list) else []
    except (TypeError, ValueError):
        return [s.strip() for s in str(v).split(",") if s.strip()]


def main(src: Path, out: Path) -> None:
    now = int(time.time() * 1000)
    catalog, prompts = [], []

    def add(kind, sid, name, desc, cat, url, price_micro=None, x402=0, meta=None):
        if not name:
            return
        catalog.append((f"{kind}:{sid}", kind, name.replace("**", "").strip(" *")[:200], (desc or "").strip()[:2000], (cat or "").strip()[:60],
                        url, price_micro, int(bool(x402)), json.dumps(meta or {}, separators=(",", ":")), now))

    for r in rows(src / "agent_memory.db", "SELECT * FROM marketplace WHERE is_active = 1"):
        endpoint = r["endpoint"] or ""
        if "example.com" in endpoint:
            continue  # test listing
        built_in = "aipaygen.com" in endpoint
        # price_usd sometimes held a monthly subscription price; show the per-call price only.
        per_call = r["price_usd"] or 0
        try:
            models = json.loads(r["pricing_models"] or "{}")
        except ValueError:
            models = {}
        if per_call >= 1:
            per_call = models.get("per_call") or 0.05
        add("listing", r["listing_id"], r["name"], r["description"], r["category"], endpoint,
            int(round(per_call * 1_000_000)), 1,
            {"provider": "AIPayGen" if built_in else "third-party",
             "runs": endpoint.replace("https://api.aipaygen.com", "") if built_in else None,
             "capabilities": as_list(r["capabilities"]), "tags": as_list(r["tags"])})

    for r in rows(src / "api_catalog.db", "SELECT * FROM discovered_apis WHERE is_active = 1"):
        add("api", r["id"], r["name"], r["description"], r["category"], r["base_url"], None, r["x402_compatible"],
            {"docs_url": r["docs_url"], "openapi_url": r["openapi_url"], "auth": r["auth_type"] if r["auth_required"] else "none",
             "sample_endpoint": r["sample_endpoint"], "source": r["source"]})

    # Skip "skills" that only wrap another vendor's model: run_skill runs on Claude, so they'd be mislabeled.
    for r in rows(src / "skills.db", "SELECT * FROM skills WHERE name NOT LIKE 'test%' AND model LIKE 'claude%'"):
        add("skill", r["id"], r["name"], r["description"], r["category"], f"{PUBLIC_PRICE_BASE}/v1/catalog/skill/{r['id']}",
            None, 0, {"source": r["source"]})
        if r["prompt_template"]:
            prompts.append((f"skill:{r['id']}", r["prompt_template"], r["input_schema"], r["output_hint"]))

    for r in rows(src / "agent_memory.db", "SELECT * FROM agent_registry"):
        add("agent", r["agent_id"], r["name"], r["description"], "", r["endpoint"], None, 0,
            {"capabilities": as_list(r["capabilities"])})

    for r in rows(src / "discovery_engine.db", "SELECT * FROM discovered_services WHERE name IS NOT NULL AND name != ''"):
        add("service", r["id"], r["name"], r["response_summary"] or "", r["service_type"], r["url"], None, 0,
            {"source": r["source"]})

    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        f.write("-- Generated by core/scripts/export_catalog_d1.py. Safe to re-run: replaces catalog rows.\n")
        f.write("DELETE FROM skill_prompts;\nDELETE FROM catalog;\n")
        def write_batched(head, data):
            # D1 rejects statements over 100 KB, so batch rows by size, not count.
            batch, size = [], 0
            for row in data:
                tup = "(" + ", ".join(q(v) for v in row) + ")"
                if batch and size + len(tup) > 90_000:
                    f.write(head + ",\n".join(batch) + ";\n")
                    batch, size = [], 0
                batch.append(tup)
                size += len(tup) + 2
            if batch:
                f.write(head + ",\n".join(batch) + ";\n")

        write_batched("INSERT OR REPLACE INTO catalog (id, kind, name, description, category, url, price_micro, x402, meta, updated_at) VALUES\n", catalog)
        write_batched("INSERT OR REPLACE INTO skill_prompts (id, prompt_template, input_schema, output_hint) VALUES\n", prompts)
        f.write("INSERT INTO catalog_fts(catalog_fts) VALUES ('rebuild');\n")
    kinds = {}
    for row in catalog:
        kinds[row[1]] = kinds.get(row[1], 0) + 1
    print(f"{len(catalog)} catalog rows {kinds}, {len(prompts)} skill prompts -> {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]).expanduser(), Path(sys.argv[2]).expanduser())
